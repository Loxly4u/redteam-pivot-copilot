"""
Engagement log — human-in-the-loop decision tracking.

Every suggestion generated by the engine must be explicitly approved or
rejected by a human operator before it is recorded as "approved". This
module never executes anything; "approved" simply means the human has
decided they will manually carry out that step themselves, outside this
tool, in their authorized lab.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

from pivot_copilot.suggestions import Suggestion


@dataclass
class Decision:
    suggestion_id: str
    technique_id: str
    target_host: str
    status: str  # "approved" or "rejected"
    operator_note: str
    decided_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class EngagementLog:
    decisions: list[Decision] = field(default_factory=list)

    def record(self, suggestion: Suggestion, approved: bool, operator_note: str = "") -> Decision:
        decision = Decision(
            suggestion_id=suggestion.suggestion_id,
            technique_id=suggestion.technique_id,
            target_host=suggestion.target_host,
            status="approved" if approved else "rejected",
            operator_note=operator_note,
        )
        self.decisions.append(decision)
        return decision

    def approved_decisions(self) -> list[Decision]:
        return [d for d in self.decisions if d.status == "approved"]

    def to_dict(self) -> dict:
        return {"decisions": [asdict(d) for d in self.decisions]}

    def save(self, path: str | Path) -> None:
        Path(path).write_text(json.dumps(self.to_dict(), indent=2), encoding="utf-8")
